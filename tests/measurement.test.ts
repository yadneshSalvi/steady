type Color = [number, number, number];
const WIDTH = 320,
  HEIGHT = 400;
const SKIN: Color = [0.38, 0.2, 0.13];
const CHANGE: Color = [0.04, -0.035, 0.015];

function landmarks(): Point[] {
  const points = Array.from({ length: 468 }, () => ({ x: 0.5, y: 0.5, z: 0 }));
  const set = (index: number, x: number, y: number) => {
    points[index] = { x, y, z: 0 };
  };
  set(234, 0.16, 0.48);
  set(454, 0.84, 0.48);
  set(10, 0.5, 0.08);
  set(152, 0.5, 0.92);
  set(1, 0.5, 0.52);
  const cheek = [
    [0.59, 0.47],
    [0.68, 0.47],
    [0.79, 0.47],
    [0.79, 0.64],
    [0.68, 0.64],
    [0.59, 0.64],
  ];
  for (const region of ["left_cheek", "right_cheek"] as const) {
    REGION_LANDMARKS[region].forEach((index, i) =>
      set(
        index,
        region === "left_cheek" ? cheek[i][0] : 1 - cheek[i][0],
        cheek[i][1],
      ),
    );
  }
  // Anatomical oval anchors produce the same known-color fixture bounds.
  for (const region of ["left_cheek", "right_cheek"] as const) {
    const side = region === "left_cheek" ? 1 : -1;
    const centerX = region === "left_cheek" ? 0.69 : 0.31;
    const offset = BLUSH_CENTROID_OFFSETS[region];
    const anchorX = centerX - offset.major * side * 0.1;
    const anchorY = 0.555 - offset.minor * 0.085;
    const anchors = CHEEK_OVAL_ANCHORS[region];
    set(anchors.medialApple, anchorX - side * (0.1 / 1.8), anchorY);
    set(anchors.lateralCheekbone, anchorX + side * (0.1 / 1.8), anchorY);
    set(anchors.lowerApple, anchorX, anchorY + 0.1);
  }
  [
    [108, 0.43, 0.2],
    [151, 0.5, 0.18],
    [337, 0.57, 0.2],
    [9, 0.5, 0.31],
    [193, 0.47, 0.35],
    [168, 0.5, 0.33],
    [417, 0.53, 0.35],
    [351, 0.535, 0.4],
    [197, 0.5, 0.42],
    [122, 0.465, 0.4],
  ].forEach(([index, x, y]) => set(index, x, y));
  REGION_LANDMARKS.lips.forEach((index, i) => {
    const angle = Math.PI + (i / REGION_LANDMARKS.lips.length) * 2 * Math.PI;
    set(index, 0.5 + Math.cos(angle) * 0.14, 0.75 + Math.sin(angle) * 0.065);
  });
  [
    78, 191, 80, 81, 82, 13, 312, 311, 310, 415, 308, 324, 318, 402, 317, 14,
    87, 178, 88, 95,
  ].forEach((index, i, indices) => {
    const angle = Math.PI + (i / indices.length) * 2 * Math.PI;
    set(index, 0.5 + Math.cos(angle) * 0.105, 0.75 + Math.sin(angle) * 0.025);
  });
  return points;
}

function inRegion(x: number, y: number, region: Region) {
  if (region === "lips") return x > 0.35 && x < 0.65 && y > 0.68 && y < 0.82;
  return (
    y > 0.47 &&
    y < 0.64 &&
    (region === "left_cheek" ? x > 0.59 && x < 0.79 : x > 0.21 && x < 0.41)
  );
}

function encodeLinear(value: number) {
  const channel = Math.max(0, Math.min(1, value));
  return Math.round(
    255 *
      (channel <= 0.0031308
        ? 12.92 * channel
        : 1.055 * channel ** (1 / 2.4) - 0.055),
  );
}

function frame(
  options: {
    region?: Region;
    intensity?: number | ((x: number, y: number) => number);
    gains?: Color;
    color?: (x: number, y: number, color: Color) => Color;
    points?: Point[];
  } = {},
): MeasurementFrame {
  const region = options.region ?? "left_cheek";
  const data = new Uint8ClampedArray(WIDTH * HEIGHT * 4);
  for (let y = 0; y < HEIGHT; y++) {
    for (let x = 0; x < WIDTH; x++) {
      const nx = (x + 0.5) / WIDTH,
        ny = (y + 0.5) / HEIGHT;
      const intensity = inRegion(nx, ny, region)
        ? typeof options.intensity === "function"
          ? options.intensity(nx, ny)
          : (options.intensity ?? 0)
        : 0;
      let color = SKIN.map(
        (value, channel) => value + CHANGE[channel] * intensity,
      ) as Color;
      color = color.map(
        (value, channel) => value * (options.gains?.[channel] ?? 1),
      ) as Color;
      if (options.color) color = options.color(nx, ny, color);
      const offset = (y * WIDTH + x) * 4;
      for (let c = 0; c < 3; c++) data[offset + c] = encodeLinear(color[c]);
      data[offset + 3] = 255;
    }
  }
  return {
    image: { width: WIDTH, height: HEIGHT, data },
    landmarks: options.points ?? landmarks(),
  };
}

function fixture(region: Region = "left_cheek") {
  const baseline = frame({ region });
  const full = frame({ region, intensity: 1 });
  const target = createMeasurementTarget(baseline, full, region);
  expect(target.valid, target.reason).toBe(true);
  return { baseline, full, target };
}

describe("independent color-science reference cases", () => {
  // The 34 published pairs are the authors' supplement, not generated by our
  // implementation. Source/attribution is recorded in evaluation-measurement.md.
  const cases = readFileSync(
    new URL("./fixtures/ciede2000.txt", import.meta.url),
    "utf8",
  )
    .trim()
    .split(/\r?\n/)
    .map((line) => line.trim().split(/\s+/).map(Number));
  it("pins all 34 independent cases", () => expect(cases).toHaveLength(34));
  it.each(cases.map((row, index) => ({ index: index + 1, row })))(
    "CIEDE2000 reference $index",
    ({ row }) => {
      const first = row.slice(0, 3) as unknown as Lab;
      const second = row.slice(3, 6) as unknown as Lab;
      expect(Math.abs(deltaE2000(first, second) - row[6])).toBeLessThan(0.0001);
      expect(Math.abs(deltaE2000(second, first) - row[6])).toBeLessThan(0.0001);
    },
  );
  it("converts sRGB transfer-function endpoints and D65 white/black", () => {
    expect(srgbChannelToLinear(0)).toBe(0);
    expect(srgbChannelToLinear(255)).toBe(1);
    expect(srgbChannelToLinear(10)).toBeCloseTo(10 / 255 / 12.92, 10);
    expect(srgbToLab([255, 255, 255])[0]).toBeCloseTo(100, 4);
    expect(srgbToLab([255, 255, 255])[1]).toBeCloseTo(0, 3);
    expect(srgbToLab([0, 0, 0])).toEqual([0, 0, 0]);
    expect(deltaE2000(linearRgbToLab(SKIN), linearRgbToLab(SKIN))).toBe(0);
  });
});

describe("local checkpoint measurement from synthetic known pixels", () => {
  it.each([0, 0.45, 1, 1.3])(
    "recovers a known color shift at intensity %s",
    (intensity) => {
      const { baseline, target } = fixture();
      const result = measureCheckpoint({
        baseline,
        checkpoint: frame({ intensity }),
        target,
      });
      expect(result.verdict, result.reason).toBe(
        intensity < 0.85 ? "build" : intensity > 1.15 ? "over" : "at_target",
      );
      expect(result.progress).toBeCloseTo(intensity, 1);
      expect(result.uniformity).toBeCloseTo(1, 5);
      expect(result.lagging).toBeNull();
      expect(result.heatmap.length).toBeGreaterThan(8);
      expect(result.deltaA).toBeGreaterThanOrEqual(0);
      expect(JSON.parse(JSON.stringify(result))).toEqual(result);
    },
  );

  it("recovers the color shift through a global linear-RGB exposure/white-balance change", () => {
    const { baseline, target } = fixture();
    const control = measureCheckpoint({
      baseline,
      checkpoint: frame({ intensity: 0.55 }),
      target,
    });
    const result = measureCheckpoint({
      baseline,
      checkpoint: frame({ intensity: 0.55, gains: [1.14, 0.86, 1.08] }),
      target,
    });
    expect(result.verdict, result.reason).toBe("build");
    // Uniform 8-bit patches have systematic channel quantization error. This
    // bound includes that error; it is not a claimed real-camera accuracy.
    expect(Math.abs(result.progress! - control.progress!)).toBeLessThan(0.06);
    expect(Math.abs(result.deltaA! - control.deltaA!)).toBeLessThan(0.5);
    expect(result.diagnostics.heldOutDeltaE00).toBeLessThan(0.5);
    expect(result.diagnostics.gains[0]).toBeCloseTo(1 / 1.14, 1);
  });

  it("abstains on a disjoint held-out patch even when the fitted forehead mean is unchanged", () => {
    const { baseline, target } = fixture();
    const checkpoint = frame({
      intensity: 0.5,
      color: (x, y, color) =>
        x > 0.46 && x < 0.54 && y > 0.32 && y < 0.43
          ? (color.map((value) => value * 0.6) as Color)
          : color,
    });
    const result = measureCheckpoint({ baseline, checkpoint, target });
    expect(result.reason).toBe("lighting_changed");
    expect(result.diagnostics.gains).toEqual([1, 1, 1]);
    expect(result.diagnostics.heldOutDeltaE00).toBeGreaterThan(4.5);
    expect(result.progress).toBeNull();
    expect(result.heatmap).toEqual([]);
  });

  it("detects a spatial lighting gradient hidden by a nearly unchanged fitted mean", () => {
    const { baseline, target } = fixture();
    const checkpoint = frame({
      intensity: 0.5,
      color: (x, y, color) =>
        y < 0.32
          ? (color.map((value) => value * (x < 0.5 ? 0.7 : 1.3)) as Color)
          : color,
    });
    const result = measureCheckpoint({ baseline, checkpoint, target });
    expect(result.reason).toBe("lighting_changed");
    expect(result.diagnostics.spatialLightingDeltaE00).toBeGreaterThan(4.5);
    expect(result.diagnostics.heldOutDeltaE00).toBeLessThan(4.5);
  });

  it("reports the lighter outer cheek and lower spatial uniformity", () => {
    const { baseline, target } = fixture();
    const result = measureCheckpoint({
      baseline,
      checkpoint: frame({ intensity: (x) => (x < 0.69 ? 0.9 : 0.2) }),
      target,
    });
    expect(result.verdict, result.reason).toBe("build");
    expect(result.lagging).toBe("outer");
    const inner = result.regionalProgress?.find(
      (part) => part.subregion === "inner",
    );
    const outer = result.regionalProgress?.find(
      (part) => part.subregion === "outer",
    );
    expect(inner?.progress).toBeGreaterThan(0.8);
    expect(outer?.progress).toBeGreaterThan(0.15);
    expect(outer?.progress).toBeLessThan(0.25);
    expect(inner?.pixels).toBeGreaterThan(100);
    expect(outer?.pixels).toBeGreaterThan(100);
    expect(result.uniformity).toBeLessThan(0.6);
    expect(
      Math.max(...result.heatmap.map((cell) => cell.progress)) -
        Math.min(...result.heatmap.map((cell) => cell.progress)),
    ).toBeGreaterThan(0.5);
  });

  it("preserves anatomical inner/outer guidance for the opposite cheek", () => {
    const { baseline, target } = fixture("right_cheek");
    const result = measureCheckpoint({
      baseline,
      checkpoint: frame({
        region: "right_cheek",
        intensity: (x) => (x > 0.31 ? 0.9 : 0.2),
      }),
      target,
    });
    expect(result.lagging).toBe("outer");
  });

  it("erodes contaminated polygon edges before measuring", () => {
    const { baseline, target } = fixture();
    const checkpoint = frame({
      intensity: 1,
      color: (x, y, color) =>
        inRegion(x, y, "left_cheek") &&
        (x < 0.596 || x > 0.784 || y < 0.476 || y > 0.634)
          ? [0.03, 0.02, 0.01]
          : color,
    });
    const result = measureCheckpoint({ baseline, checkpoint, target });
    expect(result.verdict, result.reason).toBe("at_target");
    expect(result.progress).toBeCloseTo(1, 4);
  });

  it.each(["yaw", "roll"])("abstains when %s changes", (kind) => {
    const { baseline, target } = fixture();
    let points = landmarks();
    if (kind === "yaw") points[1].x += 0.1;
    else
      points = points.map((point) => {
        const x = (point.x - 0.5) * WIDTH,
          y = (point.y - 0.5) * HEIGHT;
        const angle = (12 * Math.PI) / 180;
        return {
          x: 0.5 + (x * Math.cos(angle) - y * Math.sin(angle)) / WIDTH,
          y: 0.5 + (x * Math.sin(angle) + y * Math.cos(angle)) / HEIGHT,
          z: 0,
        };
      });
    expect(faceEligible(points)).toBe(true);
    const result = measureCheckpoint({
      baseline,
      checkpoint: frame({ intensity: 0.5, points }),
      target,
    });
    expect(result.reason).toBe("pose_changed");
    expect(result.progress).toBeNull();
  });

  it("abstains on low region resolution while the face/reference remain eligible", () => {
    const { target } = fixture();
    const points = landmarks();
    Object.values(CHEEK_OVAL_ANCHORS.left_cheek).forEach((index) => {
      points[index] = {
        x: 0.65 + (points[index].x - 0.69) * 0.02,
        y: 0.55 + (points[index].y - 0.555) * 0.02,
      };
    });
    const baseline = frame({ points });
    const result = measureCheckpoint({
      baseline,
      checkpoint: frame({ points, intensity: 1 }),
      target,
    });
    expect(result.reason).toBe("too_few_pixels");
  });

  it("abstains on an ineligible face and explicit occlusion evidence", () => {
    const { baseline, full, target } = fixture();
    expect(
      measureCheckpoint({
        baseline,
        checkpoint: { ...full, landmarks: [] },
        target,
      }).reason,
    ).toBe("ineligible_face");
    expect(
      measureCheckpoint({
        baseline,
        checkpoint: { ...full, occluded: true },
        target,
      }).reason,
    ).toBe("occluded");
    const invalid = landmarks();
    invalid[200].x = NaN;
    expect(faceEligible(invalid)).toBe(false);
    const badDepth = landmarks();
    badDepth[200].z = NaN;
    expect(faceEligible(badDepth)).toBe(false);
    expect(faceEligible(new Array<Point>(468))).toBe(false);
  });

  it("abstains on high-variance obstruction instead of reporting more pigment", () => {
    const { baseline, target } = fixture();
    const checkpoint = frame({
      color: (x, y, color) =>
        inRegion(x, y, "left_cheek")
          ? Math.floor((x * WIDTH) / 5) % 2
            ? [0.03, 0.02, 0.01]
            : [0.8, 0.75, 0.7]
          : color,
    });
    expect(measureCheckpoint({ baseline, checkpoint, target }).reason).toBe(
      "occluded",
    );
  });

  it("does not divide by a zero or near-zero target", () => {
    const baseline = frame();
    const target = createMeasurementTarget(baseline, baseline, "left_cheek");
    expect(target.valid).toBe(false);
    expect(target.reason).toBe("target_too_subtle");
    const result = measureCheckpoint({
      baseline,
      checkpoint: baseline,
      target,
    });
    expect(result.reason).toBe("target_too_subtle");
    expect(result.progress).toBeNull();
    expect(JSON.stringify(result)).not.toMatch(/NaN|Infinity/);
    expect(
      measureCheckpoint({
        baseline,
        checkpoint: baseline,
        target: { ...target, valid: true },
      }).reason,
    ).toBe("target_too_subtle");
  });

  it("cannot identify the cause of an identical region-local makeup-like color change", () => {
    const { baseline, target } = fixture();
    const makeup = frame({ intensity: 0.5 });
    const localColoredLight = frame({
      color: (x, y, color) =>
        inRegion(x, y, "left_cheek")
          ? (color.map(
              (value, channel) => value + CHANGE[channel] * 0.5,
            ) as Color)
          : color,
    });
    expect(localColoredLight.image.data).toEqual(makeup.image.data);
    const result = measureCheckpoint({
      baseline,
      checkpoint: localColoredLight,
      target,
    });
    expect(result.verdict).toBe("build");
    expect(result.progress).toBeGreaterThan(0.4);
    expect(result.diagnostics.heldOutDeltaE00).toBe(0);
  });

  it("clamps overshoot to 150% and opposite changes to zero", () => {
    const { baseline, target } = fixture();
    expect(
      measureCheckpoint({
        baseline,
        checkpoint: frame({ intensity: 2 }),
        target,
      }).progress,
    ).toBe(1.5);
    expect(
      measureCheckpoint({
        baseline,
        checkpoint: frame({ intensity: -0.3 }),
        target,
      }).progress,
    ).toBe(0);
  });

  it("uses source landmarks for pixel-aligned preview statistics", () => {
    const { baseline, full, target } = fixture();
    const again = createMeasurementTarget(
      baseline,
      { ...full, landmarks: [] },
      "left_cheek",
    );
    expect(again).toEqual(target);
  });

  it("measures lip color while excluding the inner mouth", () => {
    const { baseline, target } = fixture("lips");
    const checkpoint = frame({
      region: "lips",
      intensity: 1,
      color: (x, y, color) =>
        ((x - 0.5) / 0.09) ** 2 + ((y - 0.75) / 0.017) ** 2 < 1
          ? [0, 0, 0]
          : color,
    });
    const result = measureCheckpoint({ baseline, checkpoint, target });
    expect(result.verdict, result.reason).toBe("at_target");
    expect(result.progress).toBeCloseTo(1, 3);
    expect(result.exclusions).toHaveLength(1);
  });

  it("provides bounded normalized crops and persists scalars without image/landmark geometry", () => {
    const { baseline, full, target } = fixture();
    const result = measureCheckpoint({ baseline, checkpoint: full, target });
    const summary = summarizeMeasurement(result);
    expect(
      Object.values(summary).every(
        (value) => value === null || typeof value !== "object",
      ),
    ).toBe(true);
    expect(summary).not.toHaveProperty("heatmap");
    expect(summary).not.toHaveProperty("exclusions");
    expect(summary).not.toHaveProperty("regionalProgress");
    const crop = regionCrop(baseline.landmarks, "left_cheek")!;
    expect(crop.x).toBeGreaterThanOrEqual(0);
    expect(crop.y + crop.height).toBeLessThanOrEqual(1);
    expect(regionPolygon([], "left_cheek")).toEqual([]);
    expect(regionCrop([], "left_cheek")).toBeNull();
  });
});
